const esc=value=>String(value??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

export function applySimpleDiagrams(modules) {
  for(const diagram of learningDiagrams) {
    const module=modules.find(x=>x.id===Number(diagram.id));if(!module)continue;
    module.figure=diagram.src;module.figureAlt=diagram.alt;
    if(module.learning)module.learning.diagramText=diagram.alt;
  }
}

export function renderLearningDiagram(module) {
  const diagram=learningDiagrams.find(x=>Number(x.id)===module.id);
  if(!diagram)return '';
  const panel=diagram.panels[0],single=matchMedia('(max-width:650px)').matches;
  return `<figure class="lesson-picture" data-focus-part data-diagram="${module.id}" data-single-panel="${single}"><div class="diagram-heading"><h2>${esc(diagram.title)}</h2><button type="button" class="text-button" id="diagram-zoom">Visa större bild</button></div><div class="diagram-view-controls"><button type="button" data-diagram-mode aria-pressed="${single}">${single?'Visa hela bilden':'En bilddel i taget'}</button></div><div class="diagram-overview" ${single?'hidden':''}><img class="diagram" src="${esc(diagram.src)}" alt="${esc(diagram.alt)}"></div><div class="diagram-panel-view" ${single?'':'hidden'}><h3 class="diagram-part-title">${esc(panel.title)}</h3><svg class="diagram-fragment" viewBox="${panel.x} ${panel.y} ${panel.width} ${panel.height}" width="${panel.width}" height="${panel.height}" role="img" aria-label="${esc(panel.panelAlt||panel.title)}"><image href="${esc(diagram.src)}" width="${diagram.width}" height="${diagram.height}"/></svg><p class="diagram-part-description" data-read-block>${esc(panel.panelAlt||panel.title)}</p><div class="diagram-part-navigation"><button type="button" data-diagram-previous disabled>Föregående bilddel</button><span class="diagram-part-count" aria-live="polite">Del 1 av ${diagram.panels.length}</span><button type="button" data-diagram-next>Nästa bilddel</button></div></div><figcaption><details class="diagram-reading"><summary>Hela bilden förklarad med ord</summary><p data-read-block>${esc(diagram.alt)}</p></details></figcaption></figure>`;
}

function show(figure,index,single) {
  const diagram=learningDiagrams.find(x=>Number(x.id)===Number(figure.dataset.diagram));
  const panel=diagram.panels[index];figure.dataset.panelIndex=String(index);figure.dataset.singlePanel=String(single);
  figure.querySelector('.diagram-overview').hidden=single;figure.querySelector('.diagram-panel-view').hidden=!single;
  const mode=figure.querySelector('[data-diagram-mode]');mode.setAttribute('aria-pressed',String(single));mode.textContent=single?'Visa hela bilden':'En bilddel i taget';
  const svg=figure.querySelector('svg.diagram-fragment');svg.setAttribute('viewBox',`${panel.x} ${panel.y} ${panel.width} ${panel.height}`);svg.setAttribute('width',panel.width);svg.setAttribute('height',panel.height);svg.setAttribute('aria-label',panel.panelAlt||panel.title);
  figure.querySelector('.diagram-part-title').textContent=panel.title;figure.querySelector('.diagram-part-description').textContent=panel.panelAlt||panel.title;
  figure.querySelector('.diagram-part-count').textContent=`Del ${index+1} av ${diagram.panels.length}`;
  figure.querySelector('[data-diagram-previous]').disabled=index===0;figure.querySelector('[data-diagram-next]').disabled=index===diagram.panels.length-1;
  window.dispatchEvent(new CustomEvent('chemistry:content'));
}

export function connectDiagramPanels(root) {
  root.querySelectorAll('[data-diagram]').forEach(figure=>{
    figure.querySelector('[data-diagram-mode]').onclick=()=>show(figure,Number(figure.dataset.panelIndex||0),figure.dataset.singlePanel!=='true');
    figure.querySelector('[data-diagram-previous]').onclick=()=>show(figure,Math.max(0,Number(figure.dataset.panelIndex||0)-1),true);
    figure.querySelector('[data-diagram-next]').onclick=()=>{const diagram=learningDiagrams.find(x=>Number(x.id)===Number(figure.dataset.diagram));show(figure,Math.min(diagram.panels.length-1,Number(figure.dataset.panelIndex||0)+1),true);};
  });
}

matchMedia('(max-width:650px)').addEventListener('change',event=>document.querySelectorAll('[data-diagram]').forEach(figure=>show(figure,Number(figure.dataset.panelIndex||0),event.matches)));
